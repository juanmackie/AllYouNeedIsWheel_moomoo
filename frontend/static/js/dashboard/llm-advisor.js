/**
 * LLM Advisor Module
 *
 * Handles the AI Trade Advisor panel: triggers LLM suggestions and
 * renders the response. Lightweight — no state beyond DOM references.
 */

// DOM refs (lazy)
let generateBtn, generateLabel, spinner, statusEl, resultEl, resultTextEl, resultMetaEl, errorEl, errorTextEl;

function initElements() {
    generateBtn = document.getElementById('llm-generate-btn');
    generateLabel = document.getElementById('llm-generate-label');
    spinner = document.getElementById('llm-spinner');
    statusEl = document.getElementById('llm-status');
    resultEl = document.getElementById('llm-result');
    resultTextEl = document.getElementById('llm-result-text');
    resultMetaEl = document.getElementById('llm-result-meta');
    errorEl = document.getElementById('llm-error');
    errorTextEl = document.getElementById('llm-error-text');
}

function setLoading(loading) {
    if (!generateBtn) return;
    generateBtn.disabled = loading;
    if (spinner) spinner.classList.toggle('d-none', !loading);
    if (generateLabel) {
        generateLabel.textContent = loading ? 'Analyzing...' : 'Generate Suggestions';
    } else {
        generateBtn.textContent = loading ? 'Analyzing...' : 'Generate Suggestions';
    }
}

/**
 * Render markdown-like LLM output as safe HTML.
 * Handles headings, bold, code, lists, and line breaks.
 */
function renderMarkdown(text) {
    let html = text
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/^### (.+)$/gm, '<h6 class="fw-bold mt-2 mb-1">$1</h6>')
        .replace(/^## (.+)$/gm, '<h5 class="fw-bold mt-3 mb-1">$1</h5>')
        .replace(/^# (.+)$/gm, '<h4 class="fw-bold mt-3 mb-2">$1</h4>')
        .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
        .replace(/`([^`]+)`/g, '<code class="text-light bg-dark px-1 rounded">$1</code>')
        .replace(/^- (.+)$/gm, '<li class="ms-3">$1</li>')
        .replace(/\n{2,}/g, '</p><p class="mb-2">')
        .replace(/\n/g, '<br>');
    return '<p class="mb-2">' + html + '</p>';
}

function showResult(text, provider, model) {
    if (!resultEl || !resultTextEl || !resultMetaEl) return false;
    const cleanText = typeof text === 'string' ? text.trim() : '';
    if (!cleanText) {
        showError('AI provider returned an empty response. Try again or choose a different model.');
        return false;
    }
    resultEl.classList.remove('d-none');
    errorEl.classList.add('d-none');
    resultEl.querySelector('.alert')?.classList.add('show');
    resultTextEl.innerHTML = renderMarkdown(cleanText);
    resultMetaEl.textContent = `Generated by ${provider || 'unknown provider'}/${model || 'unknown model'}`;
    return true;
}

function showError(message) {
    if (!errorEl || !errorTextEl) return;
    resultEl.classList.add('d-none');
    errorEl.classList.remove('d-none');
    errorEl.querySelector('.alert')?.classList.add('show');
    errorTextEl.textContent = message;
}

function setUnavailable(message) {
    if (generateBtn) generateBtn.disabled = true;
    if (statusEl) statusEl.textContent = message || 'AI advisor unavailable.';
}

async function loadAdvisorStatus() {
    const response = await fetch('/api/llm/status');
    const contentType = response.headers?.get?.('content-type') || '';
    if (!contentType.includes('application/json')) {
        if (response.status === 404) {
            return {
                success: true,
                available: false,
                message: 'AI advisor status route is unavailable. Restart the local server to load the latest backend.',
            };
        }
        throw new Error(`Server returned non-JSON response (HTTP ${response.status}).`);
    }
    const payload = await response.json();
    if (!response.ok || !payload.success) {
        throw new Error(payload.error || `Request failed (HTTP ${response.status}).`);
    }
    return payload;
}

async function generateSuggestions() {
    initElements();
    if (!generateBtn) return;

    setLoading(true);
    statusEl.textContent = 'Gathering portfolio data and consulting AI...';
    resultEl.classList.add('d-none');
    errorEl.classList.add('d-none');

    try {
        const response = await fetch('/api/llm/suggestions', { method: 'POST' });

        let payload;
        try {
            payload = await response.json();
        } catch {
            showError(`Server returned non-JSON response (HTTP ${response.status}). Check the server logs.`);
            return;
        }

        if (!response.ok || !payload.success) {
            showError(payload.error || `Request failed (HTTP ${response.status}).`);
            return;
        }

        if (showResult(payload.text, payload.provider, payload.model)) {
            statusEl.textContent = 'Analysis complete.';
        } else {
            statusEl.textContent = 'No advisor output returned.';
        }
    } catch (err) {
        console.error('LLM advisor error:', err);
        showError(`Network or server error: ${err.message}`);
    } finally {
        setLoading(false);
    }
}

/**
 * Initialize the LLM advisor panel.
 * Called from dashboard.js after all other data loads.
 */
export function initializeLLMAdvisor() {
    initElements();

    const section = document.getElementById('llm-advisor-section');
    if (!section) return;

    const enabled = section.dataset.llmEnabled === 'true';
    if (!enabled) {
        if (generateBtn) generateBtn.disabled = true;
        return;
    }

    setUnavailable('Checking AI advisor configuration...');

    loadAdvisorStatus()
        .then((status) => {
            if (!status.available) {
                setUnavailable(status.message || 'AI advisor is unavailable.');
                return;
            }
            if (generateBtn) {
                generateBtn.disabled = false;
                if (!generateBtn.dataset.bound) {
                    generateBtn.dataset.bound = 'true';
                    generateBtn.addEventListener('click', generateSuggestions);
                }
            }
            if (statusEl) statusEl.textContent = 'Ready. Click "Generate Suggestions" to get AI-powered trade advice.';
        })
        .catch((err) => {
            console.warn('LLM advisor status unavailable:', err);
            setUnavailable('AI advisor status unavailable.');
        });
}
